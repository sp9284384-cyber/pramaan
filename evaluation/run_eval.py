"""Evaluation harness.

  python evaluation/run_eval.py run     # check every claim in claims.csv (uses credits; cached)
  python evaluation/run_eval.py score   # score label_sheet.csv after you fill in human_stance

Metrics that need NO hand labels: unclassified rate, status distribution, and
English-vs-Hinglish consistency (same claim in both languages should get the same status).
Metrics that need YOUR labels: status accuracy (expected_status in claims.csv) and
stance accuracy (human_stance in label_sheet.csv). Nothing is invented here.
"""
import csv
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLAIMS = HERE / "claims.csv"
RESULTS_JSON = HERE / "results.json"
LABEL_SHEET = HERE / "label_sheet.csv"
RESULTS_MD = HERE / "RESULTS.md"
STANCES = {"supports", "opposes", "insufficient"}


def load_claims(path=CLAIMS):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def evaluate(rows, check=None):
    import time
    if check is None:
        from evidence_tools.pipeline import check_claim, result_to_dict
        check = lambda text: result_to_dict(check_claim(text))
    out = []
    for i, row in enumerate(rows):
        rec = {"id": row["id"], "pair": row.get("pair", ""), "claim": row["claim"],
               "language": row.get("language", ""), "notes": row.get("notes", ""),
               "expected_status": (row.get("expected_status") or "").strip()}
        print(f"[{i+1}/{len(rows)}] Checking {row['id']} ({row.get('language')}): {row['claim']}")
        try:
            d = check(row["claim"])
            rec.update(status=d["summary"]["status"], n_sources=len(d["sources"]),
                       unclassified=d["unclassified"], llm_used=d["claim"]["llm_used"],
                       claim_en=d["claim"]["claim_en"], sources=d["sources"], error="")
            print(f"    -> Status: {d['summary']['status']} ({len(d['sources'])} sources, {d['unclassified']} unclassified)")
        except Exception as e:
            err_name = type(e).__name__
            print(f"    -> ERROR: {err_name}: {e}")
            rec.update(status="error", n_sources=0, unclassified=0, llm_used=False,
                       claim_en="", sources=[], error=err_name)
        out.append(rec)
        time.sleep(1.0)
    return out


def _rate(a, b):
    return None if not b else a / b


def compute_metrics(records):
    ok = [r for r in records if r["status"] != "error"]
    total = sum(r["n_sources"] for r in ok)
    unc = sum(r["unclassified"] for r in ok)
    pairs = {}
    for r in ok:
        if r["pair"]:
            pairs.setdefault(r["pair"], []).append(r)
    both = [v for v in pairs.values() if len(v) == 2]
    consistent = sum(1 for v in both if v[0]["status"] == v[1]["status"])
    labeled = [r for r in ok if r["expected_status"]]
    correct = sum(1 for r in labeled if r["expected_status"] == r["status"])
    return {
        "claims": len(records), "errors": len(records) - len(ok),
        "no_llm": sum(1 for r in ok if not r["llm_used"]),
        "sources": total, "unclassified": unc, "unclassified_rate": _rate(unc, total),
        "status_counts": dict(Counter(r["status"] for r in records)),
        "pairs": len(both), "pairs_consistent": consistent,
        "pair_consistency": _rate(consistent, len(both)),
        "labeled_claims": len(labeled), "status_correct": correct,
        "status_accuracy": _rate(correct, len(labeled)),
    }


def write_label_sheet(records, path=LABEL_SHEET):
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["claim_id", "claim_en", "title", "snippet", "model_stance", "model_evidence", "human_stance"])
        for r in records:
            for s in r["sources"]:
                w.writerow([r["id"], r["claim_en"], s["title"], s["snippet"], s["stance"], s["evidence"], ""])


def score_label_sheet(path=LABEL_SHEET):
    with open(path, encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f) if (r.get("human_stance") or "").strip() in STANCES]
    correct = sum(1 for r in rows if r["model_stance"] == r["human_stance"].strip())
    conf = Counter((r["model_stance"], r["human_stance"].strip()) for r in rows)
    return {"labeled": len(rows), "correct": correct, "accuracy": _rate(correct, len(rows)),
            "confusion": {f"model={a} human={b}": n for (a, b), n in sorted(conf.items())}}


def _pct(x):
    return "n/a" if x is None else f"{100 * x:.0f}%"


def write_results_md(records, m, stance=None, path=RESULTS_MD):
    L = ["# Evaluation results", "",
         "Generated by `evaluation/run_eval.py`. Numbers below are measured, not estimated.", "",
         f"- Claims run: {m['claims']} (errors: {m['errors']}, ran without an LLM key: {m['no_llm']})",
         f"- Sources retrieved: {m['sources']}; design not visible (unclassified): {m['unclassified']} ({_pct(m['unclassified_rate'])})",
         f"- English vs Hinglish consistency: {m['pairs_consistent']}/{m['pairs']} pairs got the same status ({_pct(m['pair_consistency'])})",
         f"- Status accuracy vs my labels: {m['status_correct']}/{m['labeled_claims']} ({_pct(m['status_accuracy'])})"]
    if stance:
        L.append(f"- Stance accuracy vs my labels: {stance['correct']}/{stance['labeled']} ({_pct(stance['accuracy'])})")
        L += ["", "Stance confusion (model vs human):", ""] + [f"- {k}: {v}" for k, v in stance["confusion"].items()]
    L += ["", "## Status distribution", ""] + [f"- {k}: {v}" for k, v in sorted(m["status_counts"].items())]
    L += ["", "## Per claim", "", "| id | claim | status | sources | unclassified | expected | notes |", "|---|---|---|---|---|---|---|"]
    for r in records:
        L.append(f"| {r['id']} | {r['claim']} | {r['status']} | {r['n_sources']} | {r['unclassified']} | {r['expected_status'] or '-'} | {r['notes'] or r['error'] or ''} |")
    L += ["", "## Failure cases", "", "(Add the specific failures you found here: claim id, what the tool said, what was right.)", ""]
    Path(path).write_text("\n".join(L), encoding="utf-8")


def main(argv=None):
    cmd = (argv or sys.argv[1:] or [""])[0]
    if cmd == "run":
        records = evaluate(load_claims())
        RESULTS_JSON.write_text(json.dumps(records, indent=2), encoding="utf-8")
        write_label_sheet(records)
        m = compute_metrics(records)
        write_results_md(records, m)
        print(json.dumps(m, indent=2))
        print(f"Wrote {RESULTS_MD.name}, {RESULTS_JSON.name}, {LABEL_SHEET.name}. Fill human_stance in the label sheet, then run: score")
    elif cmd == "score":
        records = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
        stance = score_label_sheet()
        write_results_md(records, compute_metrics(records), stance)
        print(json.dumps(stance, indent=2))
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
